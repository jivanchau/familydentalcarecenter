/** Matches the CSS breakpoint where the menu is a horizontal bar with hover dropdowns. */
const isDesktop = () => window.matchMedia('(min-width: 992px)').matches

function MenuItem({ item, depth }: { item: NavItem; depth: number }) {
  const [open, setOpen] = useState(false)
  const ref = useRef<HTMLLIElement>(null)

  // Close when clicking/tapping anywhere outside this item, or on Escape.
  useEffect(() => {
    if (!open) return
    const onPointer = (e: PointerEvent) => {
      if (!ref.current?.contains(e.target as Node)) setOpen(false)
    }
    const onKey = (e: KeyboardEvent) => {
      if (e.key !== 'Escape') return
      setOpen(false)
      ref.current?.querySelector('button')?.focus()
    }
    document.addEventListener('pointerdown', onPointer)
    document.addEventListener('keydown', onKey)
    return () => {
      document.removeEventListener('pointerdown', onPointer)
      document.removeEventListener('keydown', onKey)
    }
  }, [open])

  if (item.soon) {
    return (
      <li>
        <span className="nav-soon" aria-disabled="true">
          {item.label} <small>Soon</small>
        </span>
      </li>
    )
  }
  if (!item.children) {
    return (
      <li>
        <NavLink to={item.to!} end={item.to === '/'}>
          {item.label}
        </NavLink>
      </li>
    )
  }
  return (
    <li
      ref={ref}
      className={`has-sub${open ? ' is-open' : ''}`}
      // Keyboard: close once focus tabs out of this item. Desktop mouse: close when the pointer leaves.
      onBlur={(e) => !e.currentTarget.contains(e.relatedTarget) && setOpen(false)}
      onMouseLeave={() => isDesktop() && setOpen(false)}
    >
      <button type="button" aria-expanded={open} onClick={() => setOpen((o) => !o)}>
        {item.label}
        <i className={`fa-solid ${depth === 0 ? 'fa-chevron-down' : 'fa-chevron-right'}`} />
      </button>
      <ul className={`submenu depth-${depth}`}>
        {item.children.map((c) => (
          <MenuItem key={c.label} item={c} depth={depth + 1} />
        ))}
      </ul>
    </li>
  )
}

export default function Header() {
  const [menuOpen, setMenuOpen] = useState(false)
  const [scrolled, setScrolled] = useState(false)
  const { pathname } = useLocation()

  useEffect(() => {
    setMenuOpen(false)
  }, [pathname])
  useEffect(() => {
    const onScroll = () => setScrolled(window.scrollY > 60)
    window.addEventListener('scroll', onScroll, { passive: true })
    return () => window.removeEventListener('scroll', onScroll)
  }, [])

  return (
    <header className={`site-header${scrolled ? ' is-scrolled' : ''}`}>
      <TopBar />
      <div className="navbar">
        <div className="container navbar__inner">
          {/* White logo on transparent background, generated by scripts/banners/make_logo.py */}
          <Link to="/" className="brand" aria-label={`${site.name} home`}>
            <img src="/img/brand/familydentacarelogo.png" alt={`${site.name}, ${site.city}`} width={328} height={180} />
          </Link>
          <button
            className={`menu-toggle${menuOpen ? ' is-active' : ''}`}
            aria-label="Toggle menu"
            aria-expanded={menuOpen}
            onClick={() => setMenuOpen((o) => !o)}
          >
            <span />
            <span />
            <span />
          </button>
          <nav className={`menu${menuOpen ? ' is-open' : ''}`} aria-label="Main">
            <ul>
              {/* Keyed by path so every open dropdown resets after navigating to a new page. */}
              {nav.map((item) => (
                <MenuItem key={`${item.label}@${pathname}`} item={item} depth={0} />
              ))}
            </ul>
            <Link to={paths.contact} className="btn btn-light menu__cta">
              <i className="fa-regular fa-calendar" /> Book Appointment
            </Link>
          </nav>
        </div>
      </div>
    </header>
  )
}
