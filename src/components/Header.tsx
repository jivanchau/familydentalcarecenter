import { useEffect, useState } from 'react'
import { Link, NavLink, useLocation } from 'react-router-dom'
import { nav, paths, site, type NavItem } from '../config/site'

function TopBar() {
  const call = site.phones[1]
  return (
    <div className="topbar">
      <div className="container topbar__inner">
        <div className="topbar__info">
          <a href={site.mapLink} target="_blank" rel="noreferrer">
            <i className="fa-solid fa-location-dot" /> Redcross Road, {site.city}
          </a>
          <span className="topbar__days">
            <i className="fa-regular fa-clock" /> Open {site.openDays}
          </span>
        </div>
        <div className="topbar__actions">
          <a href={`tel:${call.replace(/\D/g, '')}`}>
            <i className="fa-solid fa-phone" /> {call}
          </a>
          <a href={`https://wa.me/${site.whatsapp}`} target="_blank" rel="noreferrer" className="topbar__wa">
            <i className="fab fa-whatsapp" /> WhatsApp
          </a>
        </div>
      </div>
    </div>
  )
}

function MenuItem({ item, depth }: { item: NavItem; depth: number }) {
  const [open, setOpen] = useState(false)
  if (item.soon) {
    return (
      <li>
        <span className="nav-soon" aria-disabled="true">
          {item.label} <small>Soon</small>
        </span>
      </li>
    )
  }
  if (!item.children) {
    return (
      <li>
        <NavLink to={item.to!} end={item.to === '/'}>
          {item.label}
        </NavLink>
      </li>
    )
  }
  return (
    <li className={`has-sub${open ? ' is-open' : ''}`}>
      <button type="button" aria-expanded={open} onClick={() => setOpen((o) => !o)}>
        {item.label}
        <i className={`fa-solid ${depth === 0 ? 'fa-chevron-down' : 'fa-chevron-right'}`} />
      </button>
      <ul className={`submenu depth-${depth}`}>
        {item.children.map((c) => (
          <MenuItem key={c.label} item={c} depth={depth + 1} />
        ))}
      </ul>
    </li>
  )
}

export default function Header() {
  const [menuOpen, setMenuOpen] = useState(false)
  const [scrolled, setScrolled] = useState(false)
  const { pathname } = useLocation()

  useEffect(() => {
    setMenuOpen(false)
  }, [pathname])
  useEffect(() => {
    const onScroll = () => setScrolled(window.scrollY > 60)
    window.addEventListener('scroll', onScroll, { passive: true })
    return () => window.removeEventListener('scroll', onScroll)
  }, [])

  return (
    <header className={`site-header${scrolled ? ' is-scrolled' : ''}`}>
      <TopBar />
      <div className="navbar">
        <div className="container navbar__inner">
          {/* White logo on transparent background, generated by scripts/banners/make_logo.py */}
          <Link to="/" className="brand" aria-label={`${site.name} home`}>
            <img src="/img/brand/logo-white.png" alt={`${site.name}, ${site.city}`} width={328} height={180} />
          </Link>
          <button
            className={`menu-toggle${menuOpen ? ' is-active' : ''}`}
            aria-label="Toggle menu"
            aria-expanded={menuOpen}
            onClick={() => setMenuOpen((o) => !o)}
          >
            <span />
            <span />
            <span />
          </button>
          <nav className={`menu${menuOpen ? ' is-open' : ''}`} aria-label="Main">
            <ul>
              {nav.map((item) => (
                <MenuItem key={item.label} item={item} depth={0} />
              ))}
            </ul>
            <Link to={paths.contact} className="btn btn-light menu__cta">
              <i className="fa-regular fa-calendar" /> Book Appointment
            </Link>
          </nav>
        </div>
      </div>
    </header>
  )
}
